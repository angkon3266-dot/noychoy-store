    /**
     * Inline SVG for an admin-configured icon value.
     *
     * Mirrors IconOrGlyph in the React set: a known name renders as the icon, an
     * unrecognised value (an emoji saved before the picker existed) is still
     * shown as text rather than vanishing, and an empty value falls back.
     */
    public static function svg(?string $value, string $class = 'w-6 h-6', string $fallback = 'check'): string
    {
        $name = trim((string) $value);
        $paths = static::paths();

        if ($name !== '' && ! isset($paths[$name])) {
            // Not a name we know — an old emoji, most likely. Show it.
            return '<span class="text-xl">'.e($name).'</span>';
        }

        $d = $paths[$name] ?? $paths[$fallback] ?? '';

        return '<svg class="'.e($class).'" fill="none" stroke="currentColor" stroke-width="1.5" '
            .'viewBox="0 0 24 24" aria-hidden="true">'
            .'<path stroke-linecap="round" stroke-linejoin="round" d="'.e($d).'"/></svg>';
    }
